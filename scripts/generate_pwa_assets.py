#!/usr/bin/env python3
"""Generate the iOS home-screen icons and launch (splash) images from icons/icon-mark.svg.

    pip install playwright pillow
    python scripts/generate_pwa_assets.py            # CHROMIUM_PATH=/path/to/chrome if needed

iOS wants a full-bleed, opaque, square icon (it applies its own rounded mask) and one launch
image per device size, selected by media query. The script writes the PNGs and rewrites the
<link> block between the `splash:` markers in frontend/index.html, so files and links cannot drift
(backend/tests/test_pwa_assets.py checks that they have not).
"""
import io
import os
import re
from pathlib import Path

from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
FRONT = ROOT / "frontend"
MARK = (FRONT / "icons" / "icon-mark.svg").read_text(encoding="utf-8")

INK, INK_2 = "#0b0a18", "#12112a"
# One icon, one link, named like the file iOS looks for by default: iPad and older iPhones scale the 180 px one, and a
# set of sized links is more for iOS to get wrong than to get right.
APPLE_ICON_SIZE = 180
FAVICON_SIZE = 32

# (css width, css height, device pixel ratio): portrait launch images for current iPhones and iPads.
DEVICES = (
    (440, 956, 3), (402, 874, 3), (430, 932, 3), (393, 852, 3), (428, 926, 3), (390, 844, 3),
    (375, 812, 3), (360, 780, 3), (414, 896, 3), (414, 896, 2), (414, 736, 3), (375, 667, 2), (320, 568, 2),
    (1024, 1366, 2), (834, 1194, 2), (820, 1180, 2), (834, 1112, 2), (810, 1080, 2), (768, 1024, 2),
)


def page(width, height, mark_fraction, name=None, flat=False):
    side = int(min(width, height) * mark_fraction)
    label = (f'<div style="margin-top:{int(side*0.12)}px;font:600 {int(side*0.12)}px -apple-system,system-ui,sans-serif;'
             f'color:#ecebf6;letter-spacing:.01em">{name}</div>') if name else ""
    return (f'<body style="margin:0;width:{width}px;height:{height}px;display:flex;flex-direction:column;'
            f'align-items:center;justify-content:center;background:{INK if flat else f"linear-gradient(160deg,{INK_2},{INK})"}">'
            f'<div style="width:{side}px;height:{side}px">{MARK.replace("<svg ", "<svg width=100% height=100% ")}</div>{label}</body>')


def render(browser, width, height, mark_fraction, name=None):
    pg = browser.new_page(viewport={"width": width, "height": height})
    pg.set_content(page(width, height, mark_fraction, name))
    png = pg.screenshot()
    pg.close()
    return Image.open(io.BytesIO(png)).convert("RGB")      # opaque: iOS paints transparency black


def main():
    (FRONT / "splash").mkdir(exist_ok=True)
    links = []
    with sync_playwright() as p:
        kwargs = {"executable_path": os.environ["CHROMIUM_PATH"]} if os.environ.get("CHROMIUM_PATH") else {}
        browser = p.chromium.launch(**kwargs)
        render(browser, APPLE_ICON_SIZE, APPLE_ICON_SIZE, 0.64).save(FRONT / "icons" / "apple-touch-icon.png", optimize=True)
        render(browser, FAVICON_SIZE, FAVICON_SIZE, 0.8).save(FRONT / "icons" / "favicon-32.png", optimize=True)
        for css_w, css_h, dpr in DEVICES:
            w, h = css_w * dpr, css_h * dpr
            # Render at CSS size with a device scale factor so the artwork is proportioned like the screen.
            pg = browser.new_page(viewport={"width": css_w, "height": css_h}, device_scale_factor=dpr)
            pg.set_content(page(css_w, css_h, 0.26, "3D Print Pricing", flat=True))   # flat colour: tiny PNGs
            img = Image.open(io.BytesIO(pg.screenshot())).convert("RGB")
            pg.close()
            assert img.size == (w, h), (img.size, (w, h))
            name = f"splash-{w}x{h}.png"
            img.save(FRONT / "splash" / name, optimize=True)
            links.append(f'  <link rel="apple-touch-startup-image" href="/splash/{name}" media="(device-width: {css_w}px) '
                         f'and (device-height: {css_h}px) and (-webkit-device-pixel-ratio: {dpr}) and (orientation: portrait)">')
        browser.close()
    index = (FRONT / "index.html").read_text(encoding="utf-8")
    block = "  <!-- splash:start (generated by scripts/generate_pwa_assets.py) -->\n" + "\n".join(links) + "\n  <!-- splash:end -->"
    index = re.sub(r"  <!-- splash:start.*?<!-- splash:end -->", lambda m: block, index, flags=re.S)
    (FRONT / "index.html").write_text(index, encoding="utf-8")
    print(f"Wrote the home-screen icon, the favicon and {len(DEVICES)} launch images.")


if __name__ == "__main__":
    main()
